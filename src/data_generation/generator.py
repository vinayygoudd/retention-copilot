POST_CUTOFF_LEAKAGE_TEMPLATES: List[str] = [
    "Confirmed account termination and final offboarding checklist completed after cutoff.",
    "Post-cutoff exit interview completed: customer switched to competitor platform.",
    "Final retention save offer accepted after cutoff date; account renewed.",
]


@dataclass
class GeneratedDatasetBundle:
    """Container holding all generated synthetic tables and summary metadata."""

    customers: pd.DataFrame
    usage_billing: pd.DataFrame
    support_tickets: pd.DataFrame
    campaigns_outcomes: pd.DataFrame
    metadata: Dict[str, Any]


def _sigmoid(x: np.ndarray) -> np.ndarray:
    return 1.0 / (1.0 + np.exp(-np.clip(x, -30.0, 30.0)))


def generate_synthetic_dataset(
    config: Dict[str, Any] | None = None,
    n_customers_override: int | None = None,
    save_to_disk: bool = True,
) -> GeneratedDatasetBundle:
    """Generate the complete multi-table synthetic customer retention dataset.

    Respects `prediction_cutoff_date` (e.g., 2026-06-30):
    - Features and valid history occur strictly on or before `prediction_cutoff_date`.
    - Deliberate post-cutoff tickets and post-cutoff billing events are also injected
      with timestamps > `prediction_cutoff_date` so the ETL pipeline and unit tests
      can verify that post-cutoff target leakage is properly filtered out!
    """
    if config is None:
        config = load_config()

    gen_cfg = config["data_generation"]
    n_customers = int(n_customers_override or gen_cfg.get("n_customers", 20000))
    seed = int(gen_cfg.get("random_seed", 42))
    rng = np.random.default_rng(seed)

    cutoff_dt = datetime.strptime(gen_cfg["prediction_cutoff_date"], "%Y-%m-%d")
    logger.info(
        f"Generating synthetic dataset for N={n_customers:,} customers "
        f"(seed={seed}, cutoff={cutoff_dt.strftime('%Y-%m-%d')})"
    )

    # -------------------------------------------------------------------------
    # 1. Customers & Subscription Table
    # -------------------------------------------------------------------------
    customer_ids = [f"CUST_{i:06d}" for i in range(1, n_customers + 1)]
    segments = rng.choice(
        ["SMB", "Mid_Market", "Commercial", "Enterprise"],
        size=n_customers,
        p=[0.48, 0.30, 0.14, 0.08],
    )
    regions = rng.choice(
        ["North_America", "EMEA", "APAC", "LATAM"],
        size=n_customers,
        p=[0.50, 0.26, 0.15, 0.09],
    )
    industries = rng.choice(
        ["SaaS_Tech", "Financial_Services", "Healthcare", "Retail_Ecomm", "Manufacturing", "Professional_Services"],
        size=n_customers,
        p=[0.26, 0.18, 0.14, 0.18, 0.12, 0.12],
    )

    # Plan tier correlated with segment
    plan_tiers = []
    for seg in segments:
        if seg == "SMB":
            plan_tiers.append(rng.choice(["Basic", "Standard", "Enterprise"], p=[0.65, 0.32, 0.03]))
        elif seg == "Mid_Market":
            plan_tiers.append(rng.choice(["Basic", "Standard", "Enterprise"], p=[0.25, 0.62, 0.13]))
        elif seg == "Commercial":
            plan_tiers.append(rng.choice(["Basic", "Standard", "Enterprise"], p=[0.10, 0.55, 0.35]))
        else:
            plan_tiers.append(rng.choice(["Basic", "Standard", "Enterprise"], p=[0.02, 0.28, 0.70]))
    plan_tiers = np.array(plan_tiers)

    contract_types = rng.choice(
        ["Month-to-Month", "One-Year", "Two-Year"],
        size=n_customers,
        p=[0.55, 0.28, 0.17],
    )
    payment_methods = rng.choice(
        ["Credit_Card_Auto", "ACH_Bank_Transfer", "Manual_Invoice", "Digital_Wallet"],
        size=n_customers,
        p=[0.44, 0.28, 0.18, 0.10],
    )
    auto_pay_enabled = np.where(
        payment_methods == "Manual_Invoice",
        rng.binomial(1, 0.15, size=n_customers),
        rng.binomial(1, 0.85, size=n_customers),
    )

    tenure_months = np.clip(rng.gamma(shape=2.4, scale=7.5, size=n_customers).round().astype(int), 1, 72)
    signup_dates = [
        (cutoff_dt - timedelta(days=int(tm * 30.4))).strftime("%Y-%m-%d")
        for tm in tenure_months
    ]

    base_fees = np.where(
        plan_tiers == "Basic", 29.0, np.where(plan_tiers == "Standard", 69.0, 199.0)
    )
    seats_licensed = np.where(
        plan_tiers == "Basic",
        rng.integers(1, 6, size=n_customers),
        np.where(
            plan_tiers == "Standard",
            rng.integers(3, 18, size=n_customers),
            rng.integers(10, 65, size=n_customers),
        ),
    )
    addon_mrr = np.round(rng.exponential(scale=12.0, size=n_customers) * (seats_licensed ** 0.35), 2)
    monthly_charges = np.round(base_fees + (seats_licensed - 1) * (base_fees * 0.12) + addon_mrr, 2)

    gross_margin_pct = np.where(
        plan_tiers == "Basic", 0.72, np.where(plan_tiers == "Standard", 0.78, 0.84)
    )
    expected_horizon_months = np.where(
        contract_types == "Two-Year",
        14.0,
        np.where(contract_types == "One-Year", 11.0, 8.5),
    )
    # Expected contribution value if retained (LTV_if_retained over horizon)
    expected_retained_value = np.round(monthly_charges * gross_margin_pct * expected_horizon_months, 2)

    # Latent customer health & price sensitivity factors (drive usage, tickets, and churn)
    latent_dissatisfaction = rng.normal(0.0, 1.0, size=n_customers)
    latent_price_sensitivity = rng.normal(0.0, 1.0, size=n_customers) + np.where(segments == "SMB", 0.45, -0.20)
    latent_tech_complexity = rng.normal(0.0, 1.0, size=n_customers) + np.where(plan_tiers == "Enterprise", 0.50, 0.0)

    customers_df = pd.DataFrame({
        "customer_id": customer_ids,
        "signup_date": signup_dates,
        "prediction_cutoff_date": cutoff_dt.strftime("%Y-%m-%d"),
        "segment": segments,
        "region": regions,
        "industry": industries,
        "plan_tier": plan_tiers,
        "contract_type": contract_types,
        "payment_method": payment_methods,
        "auto_pay_enabled": auto_pay_enabled,
        "tenure_months": tenure_months,
        "seats_licensed": seats_licensed,
        "monthly_charges": monthly_charges,
        "gross_margin_pct": gross_margin_pct,
        "expected_retained_value": expected_retained_value,
    })

    # -------------------------------------------------------------------------
    # 2. Pre-Cutoff Monthly Telemetry (3 pre-cutoff months + 1 post-cutoff leakage test month)
    # -------------------------------------------------------------------------
    # Months: M-2 (2026-04-30), M-1 (2026-05-31), M0 (2026-06-30 = cutoff), M+1 (2026-07-31 = post-cutoff)
    snapshot_dates = ["2026-04-30", "2026-05-31", "2026-06-30", "2026-07-31"]
    base_active_rate = np.clip(0.76 - 0.14 * latent_dissatisfaction + rng.normal(0, 0.08, n_customers), 0.08, 0.99)

    usage_records = []
    # Vectorized construction across the 4 months
    usage_trend_slope = np.clip(-0.08 * latent_dissatisfaction + rng.normal(0, 0.05, n_customers), -0.35, 0.25)

    for m_idx, snap_date in enumerate(snapshot_dates):
        is_post_cutoff = snap_date > cutoff_dt.strftime("%Y-%m-%d")
        month_factor = 1.0 + (m_idx - 1) * usage_trend_slope
        active_seats_ratio = np.clip(base_active_rate * month_factor + rng.normal(0, 0.04, n_customers), 0.02, 1.0)
        active_days = np.clip(np.round(24 * active_seats_ratio + rng.normal(0, 2.0, n_customers)), 0, 30).astype(int)
        weekly_sessions = np.clip(np.round(18 * active_seats_ratio * (seats_licensed ** 0.3) + rng.normal(0, 2.5, n_customers)), 0, 200).astype(int)
        feature_adoption_score = np.round(np.clip(0.68 * active_seats_ratio + 0.12 * (tenure_months / 36.0) + rng.normal(0, 0.07, n_customers), 0.05, 1.0), 3)
        api_calls_k = np.round(np.maximum(0.0, 15.0 * active_seats_ratio * (seats_licensed ** 0.4) + rng.normal(0, 3.0, n_customers)), 2)

        late_payment_flag = rng.binomial(
            1,
            np.clip(0.08 + 0.09 * (1 - auto_pay_enabled) + 0.05 * np.maximum(0, latent_price_sensitivity), 0.01, 0.65),
        )
        payment_failures = rng.binomial(2, np.clip(0.04 + 0.12 * late_payment_flag, 0.01, 0.50))
        billed_amount = np.round(monthly_charges * (1.0 + 0.04 * rng.binomial(1, 0.12, n_customers)), 2)

        month_df = pd.DataFrame({
            "customer_id": customer_ids,
            "snapshot_date": snap_date,
            "active_seats_ratio": np.round(active_seats_ratio, 4),
            "active_days_month": active_days,
            "weekly_sessions": weekly_sessions,
            "feature_adoption_score": feature_adoption_score,
            "api_calls_k": api_calls_k,
            "billed_amount": billed_amount,
            "late_payment_flag": late_payment_flag,
            "payment_failures": payment_failures,
            "is_post_cutoff_record": is_post_cutoff,
        })
        usage_records.append(month_df)

    usage_billing_df = pd.concat(usage_records, ignore_index=True)

    # Compute M0 vs M-2 usage change per customer for ground-truth churn generation
    m_minus_2 = usage_records[0].set_index("customer_id")
    m_zero = usage_records[2].set_index("customer_id")
    usage_drop_pct = np.clip(
        (m_minus_2["active_seats_ratio"].values - m_zero["active_seats_ratio"].values)
        / np.maximum(m_minus_2["active_seats_ratio"].values, 0.05),
        -1.0,
        1.0,
    )

    # -------------------------------------------------------------------------
    # 3. Customer Support & Complaint Tickets (Pre-Cutoff + Post-Cutoff Leakage Traps)
    # -------------------------------------------------------------------------
    ticket_lambda = np.clip(
        0.55
        + 0.65 * np.maximum(0, latent_dissatisfaction)
        + 0.35 * np.maximum(0, latent_price_sensitivity)
        + 0.30 * np.maximum(0, latent_tech_complexity),
        0.10,
        6.0,
    )
    n_tickets_per_cust = rng.poisson(lam=ticket_lambda)

    themes_list = list(COMPLAINT_THEME_TEMPLATES.keys())
    ticket_rows = []
    cust_dominant_theme = np.full(n_customers, "no_complaint", dtype=object)
    cust_severity_sum = np.zeros(n_customers, dtype=float)
    cust_unresolved_cnt = np.zeros(n_customers, dtype=int)

    ticket_counter = 1
    for idx in range(n_customers):
        k = int(n_tickets_per_cust[idx])
        if k == 0:
            continue

        # Weight theme probability by customer's latent drivers
        w_billing = 1.0 + 1.2 * max(0.0, float(latent_price_sensitivity[idx]))
        w_tech = 1.0 + 1.2 * max(0.0, float(latent_tech_complexity[idx]))
        w_support = 0.9 + 1.1 * max(0.0, float(latent_dissatisfaction[idx]))
        w_ux = 0.8 + 0.6 * max(0.0, float(latent_dissatisfaction[idx]))
        w_contract = 0.8 + (0.9 if contract_types[idx] != "Month-to-Month" else 0.4)
        probs = np.array([w_billing, w_tech, w_support, w_ux, w_contract])
        probs = probs / probs.sum()

        chosen_themes = rng.choice(themes_list, size=k, p=probs)
        # Most frequent theme for this customer
        vals, counts = np.unique(chosen_themes, return_counts=True)
        cust_dominant_theme[idx] = vals[np.argmax(counts)]

        for t_i in range(k):
            theme = str(chosen_themes[t_i])
            templates = COMPLAINT_THEME_TEMPLATES[theme]
            base_text = templates[int(rng.integers(0, len(templates)))]
            days_before = int(rng.integers(1, 90))
            t_date = (cutoff_dt - timedelta(days=days_before)).strftime("%Y-%m-%d")
            severity = int(rng.choice([1, 2, 3, 4, 5], p=[0.10, 0.25, 0.35, 0.20, 0.10]))
            resolution_hours = round(float(rng.gamma(shape=2.0 + 0.5 * severity, scale=8.0)), 1)
            is_unresolved = int(rng.binomial(1, np.clip(0.08 + 0.07 * severity, 0.05, 0.55)))
            csat_score = int(np.clip(round(5.0 - 0.65 * severity - 1.1 * is_unresolved + rng.normal(0, 0.5)), 1, 5))

            cust_severity_sum[idx] += severity
            cust_unresolved_cnt[idx] += is_unresolved

            # Enrich complaint text with contextual details for realistic NLP embeddings
            detail_suffix = (
                f" [Plan: {plan_tiers[idx]}, Severity: {severity}/5, "
                f"Resolution wait: {int(resolution_hours)}h]"
            )
            ticket_rows.append({
                "ticket_id": f"TCK_{ticket_counter:07d}",
                "customer_id": customer_ids[idx],
                "created_at": t_date,
                "ground_truth_theme": theme,
                "severity": severity,
                "resolution_time_hours": resolution_hours,
                "is_unresolved": is_unresolved,
                "csat_score": csat_score,
                "complaint_text": base_text + detail_suffix,
            })
            ticket_counter += 1

    # Add 250 post-cutoff tickets (timestamps in July 2026 > 2026-06-30) to test leakage prevention
    leakage_indices = rng.choice(n_customers, size=min(250, n_customers), replace=False)
    for idx in leakage_indices:
        days_after = int(rng.integers(2, 28))
        t_date = (cutoff_dt + timedelta(days=days_after)).strftime("%Y-%m-%d")
        text = POST_CUTOFF_LEAKAGE_TEMPLATES[int(rng.integers(0, len(POST_CUTOFF_LEAKAGE_TEMPLATES)))]
        ticket_rows.append({
            "ticket_id": f"TCK_{ticket_counter:07d}",
            "customer_id": customer_ids[int(idx)],
            "created_at": t_date,
            "ground_truth_theme": "post_cutoff_leakage",
            "severity": 5,
            "resolution_time_hours": 1.0,
            "is_unresolved": 0,
            "csat_score": 1,
            "complaint_text": text,
        })
        ticket_counter += 1

    support_tickets_df = pd.DataFrame(ticket_rows)

    # -------------------------------------------------------------------------
    # 4. Randomized Retention Campaigns, Ground-Truth CATE (Uplift), & Churn Outcome
    # -------------------------------------------------------------------------
    # Randomized assignment (RCT) across Control and 3 Retention Interventions
    campaign_names = ["none", "discount_15pct", "priority_support", "executive_bundle"]
    campaign_probs = [0.34, 0.22, 0.22, 0.22]
    assigned_campaign = rng.choice(campaign_names, size=n_customers, p=campaign_probs)
    treatment_flag = (assigned_campaign != "none").astype(int)

    cost_map = {"none": 0.0, "discount_15pct": 28.0, "priority_support": 45.0, "executive_bundle": 85.0}
    intervention_cost = np.array([cost_map[c] for c in assigned_campaign], dtype=float)

    # Baseline (Control) Churn Logit — combines behavioral, contract, billing, and NLP complaint signals
    is_mtm = (contract_types == "Month-to-Month").astype(float)
    is_two_yr = (contract_types == "Two-Year").astype(float)
    m0_active_ratio = m_zero["active_seats_ratio"].values
    m0_late = m_zero["late_payment_flag"].values
    m0_fail = m_zero["payment_failures"].values

    complaint_theme_risk = np.where(
        cust_dominant_theme == "billing_and_pricing",
        0.55,
        np.where(
            cust_dominant_theme == "technical_outage_and_bugs",
            0.65,
            np.where(
                cust_dominant_theme == "support_responsiveness",
                0.70,
                np.where(
                    cust_dominant_theme == "account_and_contract_flexibility",
                    0.50,
                    np.where(cust_dominant_theme == "missing_features_and_ux", 0.35, -0.25),
                ),
            ),
        ),
    )

    baseline_logit = (
        -1.55
        + 0.95 * is_mtm
        - 0.75 * is_two_yr
        - 0.028 * (tenure_months - 15.0)
        + 2.15 * np.maximum(0.0, usage_drop_pct)
        - 1.65 * (m0_active_ratio - 0.65)
        + 0.48 * m0_late
        + 0.35 * m0_fail
        + 0.16 * np.minimum(cust_severity_sum, 18.0)
        + 0.38 * np.minimum(cust_unresolved_cnt, 4)
        + complaint_theme_risk
        + 0.0035 * (monthly_charges - 75.0) * is_mtm
        + rng.normal(0.0, 0.25, size=n_customers)
    )
    true_prob_churn_no_treatment = _sigmoid(baseline_logit)

    # Ground-Truth Heterogeneous Treatment Effect (True Incremental Retention Probability = P(churn|0) - P(churn|1))
    # Crucial realistic uplift dynamics:
    # - Persuadables: Medium-to-high churn risk (0.25 to 0.78), Month-to-Month or 1-Yr, billing/support/tech issues
    # - Sure Things: Low churn risk (< 0.18) -> near-zero uplift
    # - Lost Causes: Extremely high churn risk (> 0.88) with multiple unresolved tickets -> very low uplift
    # - Sleeping Dogs: Customers with rigid contract complaints or very low risk disturbed by aggressive sales outreach -> slight negative uplift
    persuadable_window = np.exp(-((true_prob_churn_no_treatment - 0.52) ** 2) / (2 * (0.22 ** 2)))
    theme_uplift_bonus = np.where(
        cust_dominant_theme == "billing_and_pricing",
        0.095,
        np.where(
            cust_dominant_theme == "support_responsiveness",
            0.085,
            np.where(
                cust_dominant_theme == "technical_outage_and_bugs",
                0.065,
                np.where(cust_dominant_theme == "account_and_contract_flexibility", -0.025, 0.035),
            ),
        ),
    )
    sleeping_dog_penalty = np.where(
        (true_prob_churn_no_treatment < 0.14) & (contract_types != "Month-to-Month") & (n_tickets_per_cust == 0),
        -0.035,
        0.0,
    )

    # Base CATE (if treated with standard intervention)
    true_base_uplift = (
        0.135 * persuadable_window * (0.65 + 0.55 * is_mtm)
        + theme_uplift_bonus * persuadable_window
        + sleeping_dog_penalty
    )
    true_base_uplift = np.clip(true_base_uplift, -0.06, 0.28)

    # Campaign-specific multiplier based on alignment between customer issue and offer
    campaign_multiplier = np.ones(n_customers, dtype=float)
    for idx in range(n_customers):
        camp = assigned_campaign[idx]
        dom = cust_dominant_theme[idx]
        if camp == "none":
            campaign_multiplier[idx] = 0.0
        elif camp == "discount_15pct":
            campaign_multiplier[idx] = 1.15 if dom == "billing_and_pricing" else 0.85
        elif camp == "priority_support":
            campaign_multiplier[idx] = 1.20 if dom in ("support_responsiveness", "technical_outage_and_bugs") else 0.95
        elif camp == "executive_bundle":
            campaign_multiplier[idx] = 1.30

    # Realized uplift for the assigned treatment vs hypothetical average treatment uplift
    true_treatment_uplift = np.clip(true_base_uplift * 1.05, -0.06, true_prob_churn_no_treatment - 0.01)
    realized_uplift = np.where(
        treatment_flag == 1,
        np.clip(true_base_uplift * campaign_multiplier, -0.06, true_prob_churn_no_treatment - 0.01),
        0.0,
    )

    true_prob_churn_if_treated = np.clip(true_prob_churn_no_treatment - true_treatment_uplift, 0.01, 0.99)
    realized_prob_churn = np.clip(true_prob_churn_no_treatment - realized_uplift, 0.01, 0.99)

    churned = rng.binomial(1, realized_prob_churn)
    retained = 1 - churned

    outcome_dates = [
        (cutoff_dt + timedelta(days=int(rng.integers(5, 58)))).strftime("%Y-%m-%d")
        for _ in range(n_customers)
    ]

    campaigns_outcomes_df = pd.DataFrame({
        "customer_id": customer_ids,
        "campaign_assigned_date": cutoff_dt.strftime("%Y-%m-%d"),
        "outcome_recorded_date": outcome_dates,
        "assigned_campaign": assigned_campaign,
        "treatment_flag": treatment_flag,
        "intervention_cost": intervention_cost,
        "churned": churned,
        "retained": retained,
        "true_baseline_churn_prob": np.round(true_prob_churn_no_treatment, 5),
        "true_treated_churn_prob": np.round(true_prob_churn_if_treated, 5),
        "true_uplift_retention": np.round(true_treatment_uplift, 5),
        "dominant_complaint_theme_gt": cust_dominant_theme,
    })

    metadata = {
        "n_customers": n_customers,
        "n_usage_records": len(usage_billing_df),
        "n_support_tickets": len(support_tickets_df),
        "prediction_cutoff_date": cutoff_dt.strftime("%Y-%m-%d"),
        "overall_churn_rate": float(churned.mean()),
        "control_churn_rate": float(churned[treatment_flag == 0].mean()),
        "treated_churn_rate": float(churned[treatment_flag == 1].mean()),
        "empirical_ate_retention": float(
            churned[treatment_flag == 0].mean() - churned[treatment_flag == 1].mean()
        ),
        "mean_true_uplift": float(true_treatment_uplift.mean()),
    }

    if save_to_disk:
        raw_dir = get_project_root() / config["etl"]["raw_dir"]
        raw_dir.mkdir(parents=True, exist_ok=True)
        customers_df.to_parquet(raw_dir / "customers.parquet", index=False)
        usage_billing_df.to_parquet(raw_dir / "usage_billing.parquet", index=False)
        support_tickets_df.to_parquet(raw_dir / "support_tickets.parquet", index=False)
        campaigns_outcomes_df.to_parquet(raw_dir / "campaigns_outcomes.parquet", index=False)
        logger.info(
            f"Saved raw synthetic tables to {raw_dir} | "
            f"Overall churn={metadata['overall_churn_rate']:.2%}, "
            f"Control churn={metadata['control_churn_rate']:.2%}, "
            f"Treated churn={metadata['treated_churn_rate']:.2%}, "
            f"Empirical ATE={metadata['empirical_ate_retention']:.2%}"
        )

    return GeneratedDatasetBundle(
        customers=customers_df,
        usage_billing=usage_billing_df,
        support_tickets=support_tickets_df,
        campaigns_outcomes=campaigns_outcomes_df,
        metadata=metadata,
    )
