"""Synthetic Data Generator for Retention Copilot.

Generates a configurable, realistic B2B/B2C SaaS & Telecom-style subscription dataset
(default: 20,000 customers) with:
- Customer demographics & subscription tiers (`customers.parquet`)
- Monthly usage & billing telemetry (`usage_billing.parquet`)
- Timestamped customer support complaint tickets (`support_tickets.parquet`)
- Randomized retention campaign assignment (`campaigns_and_outcomes.parquet`)
- Known ground-truth baseline churn risk, heterogeneous treatment effects (CATE/ITE),
  and strict pre-cutoff vs post-cutoff timestamps to test target leakage prevention.

NOTE: All records generated by this module are synthetic and simulated for portfolio
and analytical demonstration purposes.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime, timedelta
from pathlib import Path
from typing import Any, Dict, List, Tuple

import numpy as np
import pandas as pd

from src.utils.config_loader import get_logger, get_project_root, load_config

logger = get_logger("data_generation.generator")


