    shap_global_df = pd.read_parquet(processed / "shap_global_importance.parquet")
    shap_cust_df = pd.read_parquet(processed / "customer_shap_values.parquet")
    clusters_df = pd.read_parquet(processed / "complaint_cluster_summary.parquet")
    uplift_curves_df = pd.read_parquet(processed / "uplift_policy_curves.parquet")
