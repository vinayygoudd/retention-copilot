    k1.metric("Test Empirical ATE (Retention Lift)", f"+{ate['empirical_uplift']:.2%}", f"p = {ate['p_value']:.2e}")
    k2.metric("95% Confidence Interval (ATE)", f"[{ate['ci_95_lower']:.2%}, {ate['ci_95_upper']:.2%}]")
